#!/usr/bin/env python3
"""Generate C++ golden vectors from the Python reference codec.

The Python codec in ``tools/reference/protocol.py``
is the reference implementation. This script runs it and emits ``tests/vectors.h``
so the C++ port can be checked against exactly the same bytes.

Run from anywhere:

    python3 tools/generate_vectors.py
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PROTOCOL_DIR = REPO_ROOT / "tools" / "reference"
sys.path.insert(0, str(PROTOCOL_DIR))

import protocol  # noqa: E402

OUT_PATH = Path(__file__).resolve().parents[1] / "tests" / "vectors.h"


def c_array(name: str, data: bytes) -> str:
    values = ", ".join(f"0x{byte:02X}" for byte in data)
    return f"inline constexpr unsigned char {name}[] = {{{values}}};\n"


def main() -> None:
    adv_18 = bytes.fromhex("00 78563412 efcdab00 00 11223344 ff 0102 27")
    adv_20 = adv_18[:10] + b"\x00\x00" + adv_18[10:]

    vectors = {
        "ADV_18": adv_18,
        "ADV_20": adv_20,
        "CMD_AUTH": protocol.command(
            protocol.CMD_AUTH_MOBILE_PHONE_A, b"+27821"
        ),
        "CMD_CHANGE_PARAMS": protocol.command(
            protocol.CMD_CHANGE_BLE_CONNECTION_PARAMETERS,
            struct.pack(">4H", 10, 12, 0, 4000),
        ),
        "CMD_TRIGGER_OPEN": protocol.command(
            protocol.CMD_TRIGGER, struct.pack("<H", protocol.TRIGGER_ONLY_OPEN)
        ),
        "CMD_STOP": protocol.command(protocol.CMD_STOP_DOOR_MOTION),
        "PHONE": protocol.encode_phone("+27821", bytes.fromhex("01020304")),
        "SDO5_V3": bytes.fromhex(
            "00 1a 8c 00 01020100 fa00 02 00 2c01 01 00 04 03 00 03 05 06 00 00 3412 7856"
        ),
        "SDO4_V2": bytes.fromhex(
            "00 16 8c 00 00000000 7d00 00 09 01 03 00 00 00 01 02 00 3412 7856"
        ),
        "SDO5_V4": bytes.fromhex(
            "00 2e a4 00 00000000 fa00 00 00 0000 00 00 03 00 00 00 00 00 00 00 0000 0000"
            " 78563412" + " 00" * 16
        ),
    }

    lines = [
        "// Auto-generated by tools/generate_vectors.py. Do not edit by hand.",
        "#pragma once",
        "",
        "namespace vectors {",
        "",
    ]
    for name, data in vectors.items():
        lines.append(c_array(name, data))
    lines += ["", "}  // namespace vectors", ""]
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(vectors)} vectors)")


if __name__ == "__main__":
    main()
